# --------------------------------------------------------------------------
# small arithmetic helpers (the counting side of section 8)
# --------------------------------------------------------------------------

def prime_factors(n):
    """The distinct primes dividing ``n``."""
    out, m, p = [], n, 2
    while p * p <= m:
        if m % p == 0:
            out.append(p)
            while m % p == 0:
                m //= p
        p += 1
    if m > 1:
        out.append(m)
    return out


def factorisation(n):
    """``n`` as ``(p, exponent)`` pairs."""
    out, m, p = [], n, 2
    while p * p <= m:
        if m % p == 0:
            e = 0
            while m % p == 0:
                m //= p
                e += 1
            out.append((p, e))
        p += 1
    if m > 1:
        out.append((m, 1))
    return out


def dedekind_psi(n):
    """psi(n) = n prod_{p | n} (1 + 1/p), the index of Gamma_0(n)."""
    r = n
    for p in prime_factors(n):
        r = r // p * (p + 1)
    return r


def squarefree_divisors(n):
    """The squarefree divisors of ``n`` (including 1)."""
    divs = [1]
    for p in prime_factors(n):
        divs += [d * p for d in divs]
    return sorted(divs)


def dedekind_psi_divisor_sum(n):
    """sum over squarefree d | n of n/d, the divisor-sum presentation."""
    return sum(n // d for d in squarefree_divisors(n))


def prim_coset_reps(n):
    """The triples (a, b, d) of base/020 section 1."""
    out = []
    for d in range(1, n + 1):
        if n % d:
            continue
        a = n // d
        for b in range(d):
            if gcd(a, gcd(b, d)) == 1:
                out.append((a, b, d))
    return out


def fibre_value(a, d):
    """h(a, d) = (d/g) phi(g), g = gcd(a, d): the number of b < d coprime to g."""
    g = gcd(a, d)
    return (d // g) * int(totient(g))


def G(n):
    """G(n) = sum over ad = n of the fibre value h(a, d)."""
    return sum(fibre_value(a, n // a) for a in range(1, n + 1) if n % a == 0)


# --------------------------------------------------------------------------
# formatting helpers
# --------------------------------------------------------------------------

def fmt(M):
    return f"[[{M[0][0]}, {M[0][1]}], [{M[1][0]}, {M[1][1]}]]"


def fmt_sym(M):
    """Format a sympy matrix, keeping rational entries such as 1/12."""
    return "[" + ", ".join(
        "[" + ", ".join(str(M[i, j]) for j in range(M.cols)) + "]"
        for i in range(M.rows)) + "]"


def diag_mat(a, d):
    return [[a, 0], [0, d]]


def inv_sl2(M):
    """Inverse of a matrix of determinant 1."""
    return [[M[1][1], -M[0][1]], [-M[1][0], M[0][0]]]


def quotient_profile(M):
    """(d1, d2, {order: count}) for the group Z^2 / (row lattice of M)."""
    _, D, _ = smith2(M)
    d1, d2 = D[0][0], D[1][1]
    orders = {}
    for x in range(d1):
        for y in range(d2):
            ox = 1 if x == 0 else d1 // gcd(x, d1)
            oy = 1 if y == 0 else d2 // gcd(y, d2)
            o = lcm(ox, oy)
            orders[o] = orders.get(o, 0) + 1
    return d1, d2, orders


def is_unimodular_by_bezout(n, pair):
    """Brute force: does there exist (x, y) with x*a + y*c = 1 mod n?"""
    a, c = pair
    return any((x * a + y * c - 1) % n == 0
               for x in range(n) for y in range(n))


def sl2_zmod(n):
    """All of SL_2(Z/n), enumerated by brute force over the n^4 tuples."""
    return [g for g in ((a, b, c, d)
                        for a in range(n) for b in range(n)
                        for c in range(n) for d in range(n))
            if (g[0] * g[3] - g[1] * g[2] - 1) % n == 0]


